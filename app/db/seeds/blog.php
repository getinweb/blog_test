<?php

declare(strict_types=1);

$categories = [
    'php' => ['name' => 'PHP', 'description' => 'Язык, структура приложения и работа с данными.'],
    'mysql' => ['name' => 'MySQL', 'description' => 'Запросы, связи между таблицами и хранение данных.'],
    'scss' => ['name' => 'SCSS', 'description' => 'Стили страниц, компоненты и организация исходников.'],
    'notes' => ['name' => 'Заметки', 'description' => 'Здесь появятся новые материалы. Пока категория пуста.'],
];
$topics = [
    'php' => [
        'Структура небольшого PHP-приложения', 'Единая точка входа', 'Настройки окружения',
        'Типы аргументов и возвращаемых значений', 'Контейнер зависимостей', 'Интерфейсы репозиториев',
        'Шаблоны Smarty', 'Обработка ошибок', 'Работа с датами', 'Интеграционные тесты',
    ],
    'mysql' => [
        'Таблицы категорий и статей', 'Связь многие ко многим', 'Подготовленные запросы',
        'Сортировка по дате публикации', 'Пагинация списка статей', 'Подсчёт просмотров',
        'Внешние ключи', 'Миграции схемы', 'Выборка похожих статей', 'Тестовая база данных',
    ],
    'scss' => [
        'Организация SCSS-файлов', 'Сброс стилей браузера', 'Типографика статьи',
        'Карточка публикации', 'Сетка главной страницы', 'Навигация по категориям',
        'Оформление пагинации', 'Адаптивные изображения', 'Сборка CSS', 'Стили пустых состояний',
    ],
];
$images = ['php' => 'images/php.png', 'mysql' => 'images/mysql.jpg', 'scss' => 'images/scss.webp'];
$start = new DateTimeImmutable('2026-09-01 12:00:00', new DateTimeZone('UTC'));
$articles = [];

foreach ($topics as $category => $titles) {
    foreach ($titles as $title) {
        $index = count($articles);
        $articleCategories = [$category];

        if ($category === 'mysql') {
            $articleCategories[] = 'php';
        } elseif ($category === 'scss' && $index % 2 === 0) {
            $articleCategories[] = 'mysql';
        }

        $articles[] = [
            'image' => $images[$category],
            'title' => $title,
            'description' => 'Демонстрационный материал: ' . mb_strtolower($title, 'UTF-8') . '.',
            'text' => $title . "\n\nЭтот материал входит в демонстрационный набор блога. "
                . "На его примере можно проверить отображение заголовка, описания и основного текста.\n\n"
                . "У статьи есть изображение, дата публикации и счётчик просмотров. "
                . "Связи с категориями позволяют проверить списки и подбор похожих материалов.\n\n"
                . 'Текст хранится без HTML-разметки и выводится с экранированием.',
            'published_at' => $start->modify('+' . intdiv($index, 2) . ' days')->format('Y-m-d H:i:s'),
            'views' => ($index % 6) * 25,
            'categories' => $articleCategories,
        ];
    }
}

return ['categories' => $categories, 'articles' => $articles];
